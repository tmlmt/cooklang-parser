import { createRegex } from "human-regex";

/** Matches all top-level metadata keys in frontmatter content */
export const metadataKeyRegex = /^([^:\n]+?):/gm;

/** Matches a number (integer or decimal, optionally negative) */
export const numericValueRegex = /^-?\d+(\.\d+)?$/;

/** Creates a regex to match a nested YAML-style object for a given key 
 * 
 * Nested properties should be indented at least by one space and can be nested arbitrarily deep. Tabs are not allowed for indentation.
 * Lines can be key-value pairs or list items (starting with `-`).
*/
export const nestedMetaVarRegex = (varName: string): RegExp =>
  new RegExp(
    `^${varName}:\\s*\\r?\\n((?:[ ]+.+(?:\\r?\\n|$))+)`,
    "m",
  );

export const metadataRegex = createRegex()
  .literal("---").newline()
  .startCaptureGroup().anyCharacter().zeroOrMore().optional().endGroup()
  .newline().literal("---")
  .dotAll().toRegExp();

export const scalingMetaValueRegex = (varName: string): RegExp => createRegex()
  .startAnchor()
  .literal(varName)
  .literal(":")
  .anyOf("\\t ").zeroOrMore()
  .startCaptureGroup()
    .startCaptureGroup()
      .notAnyOf(",\\n").oneOrMore()
    .endGroup()
    .startGroup()
      .literal(",")
      .whitespace().zeroOrMore()
      .startCaptureGroup()
        .anyCharacter().oneOrMore()
      .endGroup()
    .endGroup().optional()
  .endGroup()
  .endAnchor()
  .multiline()
  .toRegExp()

const nonWordChar = "\\s@#~\\[\\]{(,;:!?"
const nonWordCharStrict = "\\s@#~\\[\\]{(,;:!?|"

export const ingredientWithAlternativeRegex = createRegex()
  .literal("@")
  .startNamedGroup("ingredientModifiers")
    .anyOf("@\\-&?").zeroOrMore()
  .endGroup().optional()
  .startNamedGroup("ingredientRecipeAnchor")
    .literal("./")
  .endGroup().optional()
  .startGroup()
    .startGroup()
      .startNamedGroup("mIngredientName")
        .notAnyOf(nonWordChar).oneOrMore()
        .startGroup()
          .whitespace().oneOrMore().notAnyOf(nonWordChar).oneOrMore()
        .endGroup().oneOrMore()
      .endGroup()
      .positiveLookahead("\\s*(?:\\{[^\\}]*\\}|\\([^)]*\\))")
    .endGroup()
    .or()
    .startNamedGroup("sIngredientName")
      .notAnyOf(nonWordChar).zeroOrMore()
      .notAnyOf("\\."+nonWordChar)
    .endGroup()
  .endGroup()
  .startGroup()
    .literal("{")
    .startNamedGroup("ingredientQuantityModifier")
      .literal("=").exactly(1)
    .endGroup().optional()
    .startNamedGroup("ingredientQuantity")
      .startGroup()
        .notAnyOf("}|%").oneOrMore()
      .endGroup().optional()
      .startGroup()
        .literal("%")
        .notAnyOf("|}").oneOrMore().lazy()
      .endGroup().optional()
      .startGroup()
        .literal("|")
        .notAnyOf("}").oneOrMore().lazy()
      .endGroup().zeroOrMore()
    .endGroup()
    .literal("}")
  .endGroup().optional()
  .startGroup()
    .literal("(")
    .startNamedGroup("ingredientPreparation")
      .notAnyOf(")").oneOrMore().lazy()
    .endGroup()
    .literal(")")
  .endGroup().optional()
  .startGroup()
    .literal("[")
    .startNamedGroup("ingredientNote")
      .notAnyOf("\\]").oneOrMore().lazy()
    .endGroup()
    .literal("]")
  .endGroup().optional()
  .startNamedGroup("ingredientAlternative")
    .startGroup()
      .literal("|")
      .startGroup()
        .anyOf("@\\-&?").zeroOrMore()
      .endGroup().optional()
      .startGroup()
        .literal("./")
      .endGroup().optional()
      .startGroup()
        .startGroup()
          .startGroup()
            .notAnyOf(nonWordChar).oneOrMore()
            .startGroup()
              .whitespace().oneOrMore().notAnyOf(nonWordChar).oneOrMore()
            .endGroup().oneOrMore()
          .endGroup()
          .positiveLookahead("\\s*(?:\\{[^\\}]*\\}|\\([^)]*\\))")
        .endGroup()
        .or()
        .startGroup()
          .notAnyOf(nonWordChar).oneOrMore()
        .endGroup()
      .endGroup()
      .startGroup()
        .literal("{")
        .startGroup()
          .literal("=").exactly(1)
        .endGroup().optional()
        .startGroup()
          .notAnyOf("}%").oneOrMore()
        .endGroup().optional()
        .startGroup()
          .literal("%")
          .startGroup()
            .notAnyOf("}").oneOrMore().lazy()
          .endGroup()
        .endGroup().optional()
        .literal("}")
      .endGroup().optional()
      .startGroup()
        .literal("(")
        .startGroup()
          .notAnyOf(")").oneOrMore().lazy()
        .endGroup()
        .literal(")")
      .endGroup().optional()
      .startGroup()
        .literal("[")
        .startGroup()
          .notAnyOf("\\]").oneOrMore().lazy()
        .endGroup()
        .literal("]")
      .endGroup().optional()
    .endGroup().zeroOrMore()
  .endGroup()
  .toRegExp();

export const inlineIngredientAlternativesRegex = new RegExp("\\|" + ingredientWithAlternativeRegex.source.slice(1))

export const quantityAlternativeRegex = createRegex()
  .startNamedGroup("quantity")
    .notAnyOf("}|%").oneOrMore()
  .endGroup().optional()
  .startGroup()
    .literal("%")
    .startNamedGroup("unit")
      .notAnyOf("|}").oneOrMore()
    .endGroup()
  .endGroup().optional()
  .startGroup()
    .literal("|")
    .startNamedGroup("alternative")
      .startGroup()
        .notAnyOf("}").oneOrMore()
      .endGroup().zeroOrMore()
    .endGroup()
  .endGroup().optional()
  .toRegExp()
  
