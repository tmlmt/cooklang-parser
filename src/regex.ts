const timerRegex = createRegex()
  .literal("~")
  .startNamedGroup("timerName")
    .anyCharacter().zeroOrMore().lazy()
  .endGroup()
  .literal("{")
  .startNamedGroup("timerQuantity")
    .anyCharacter().oneOrMore().lazy()
  .endGroup()
  .startGroup()
    .literal("%")
    .startNamedGroup("timerUnit")
      .anyCharacter().oneOrMore().lazy()
    .endGroup()
  .endGroup().optional()
  .literal("}")
  .toRegExp()

export const arbitraryScalableRegex = createRegex()
  .literal("{{")
  .startGroup()
    .startNamedGroup("arbitraryName")
      .notAnyOf("}:%").oneOrMore()
    .endGroup()
    .literal(":")
  .endGroup().optional()
  .startNamedGroup("arbitraryQuantity")
    .startGroup()
      .notAnyOf("}|%").oneOrMore()
    .endGroup().optional()
    .startGroup()
      .literal("%")
      .notAnyOf("|}").oneOrMore().lazy()
    .endGroup().optional()
    .startGroup()
      .literal("|")
      .notAnyOf("}").oneOrMore().lazy()
    .endGroup().zeroOrMore()
  .endGroup()
  .literal("}}")
  .toRegExp();

export const tokensRegex = new RegExp(
  [
    ingredientWithGroupKeyRegex,
    ingredientWithAlternativeRegex,
    cookwareRegex,
    timerRegex,
    arbitraryScalableRegex
  ]
    .map((r) => r.source)
    .join("|"),
  "gu",
);

export const commentRegex = createRegex()
  .literal("--")
  .anyCharacter().zeroOrMore()
  .global()
  .toRegExp();

export const blockCommentRegex = createRegex()
  .literal("[-")
  .anyCharacter().zeroOrMore().lazy()
  .literal("-]")
  .whitespace().zeroOrMore()
  .global()
  .toRegExp();

export const shoppingListRegex = createRegex()
  .literal("[")
  .startNamedGroup("name")
    .anyCharacter().oneOrMore()
  .endGroup()
  .literal("]")
  .newline()
  .startNamedGroup("items")
    .anyCharacter().zeroOrMore().lazy()
  .endGroup()
  .startGroup()
    .newline().newline()
      .or()
    .endAnchor()
  .endGroup()
  .global()
  .toRegExp()

export const rangeRegex = createRegex()
  .startAnchor()
  .digit().oneOrMore()
  .startGroup()
  .anyOf(".,/").exactly(1)
    .digit().oneOrMore()
  .endGroup().optional()
  .literal("-")
  .digit().oneOrMore()
  .startGroup()
    .anyOf(".,/").exactly(1)
    .digit().oneOrMore()
  .endGroup().optional()
  .endAnchor()
  .toRegExp()

export const numberLikeRegex = createRegex()
  .startAnchor()
  .digit().oneOrMore()
  .startGroup()
    .anyOf(".,/").exactly(1)
    .digit().oneOrMore()
  .endGroup().optional()
  .endAnchor()
  .toRegExp()

export const floatRegex = createRegex()
  .startAnchor()
  .digit().oneOrMore()
  .startGroup()
    .anyOf(".").exactly(1)
    .digit().oneOrMore()
  .endGroup().optional()
  .endAnchor()
  .toRegExp()